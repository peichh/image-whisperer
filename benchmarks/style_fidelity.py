#!/usr/bin/env python3
"""Style fidelity benchmark (prompt level) and the three-axis visual verdict rule.

Prompt arms per case:
  A  raw request
  B  label stacking: request + generic "premium" style words
  S  semantic-only: a good content prompt with no aesthetic translation
  C  Image Whisperer with aesthetic translation
Usage: python3 benchmarks/style_fidelity.py [--report benchmarks/style-fidelity/REPORT.md]
"""
import argparse
import json
import re
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import run as base  # noqa: E402

CASES = HERE / "style-fidelity" / "cases.jsonl"
FIXTURES = HERE / "style-fidelity" / "rubric-fixtures.jsonl"
LABEL_SUFFIX = ", premium art style, masterpiece, cinematic, stunning, high quality, trending on artstation"
LABELS = [r"premium", r"masterpiece", r"cinematic", r"high[- ]quality", r"best quality", r"stunning", r"trending",
          r"ghibli", r"shinkai", r"kyoto animation", r"ufotable", r"pixar", r"disney", r"\baesthetic\b", r"artsy|อาร์ต"]
NEGATION = re.compile(r"\b(not|no|never|without|rather than|instead of|avoid|less)\b[^.,;:—]*", re.I)

# Visual verdict thresholds (core/quality-critic.md section E)
MIN_SEMANTIC, MIN_AESTHETIC, MIN_EXECUTION = 4, 4, 3


def verdict(semantic: int, aesthetic: int, execution: int) -> str:
    """Three-axis verdict. Right content in the wrong style is never a success."""
    for v in (semantic, aesthetic, execution):
        if not 1 <= v <= 5:
            raise ValueError("scores are 1-5")
    if semantic >= MIN_SEMANTIC and aesthetic >= MIN_AESTHETIC and execution >= MIN_EXECUTION:
        return "success"
    if semantic >= MIN_SEMANTIC and aesthetic < MIN_AESTHETIC:
        return "content_correct_style_off"
    if semantic < MIN_SEMANTIC and aesthetic >= MIN_AESTHETIC:
        return "style_correct_content_off"
    if execution < MIN_EXECUTION and semantic >= MIN_SEMANTIC and aesthetic >= MIN_AESTHETIC:
        return "weak_execution"
    return "fail"


def positive(text: str) -> str:
    """Drop negated phrases (up to the next comma or sentence break) and Midjourney `--no` lists,
    so 'not glossy' does not count as asking for gloss."""
    return NEGATION.sub(" ", re.sub(r"--no\s[^-]*", " ", text))


def score(case, prompt, negative=""):
    t = prompt
    sem = sum(bool(re.search(k, t, re.I)) for k in case["keep"]) / len(case["keep"])
    axes = case["axes"]
    pos = positive(t)
    hit = [a for a, rx in axes.items() if re.search(rx, pos, re.I)]
    cov = len(hit) / len(axes)
    labels = [l for l in LABELS if re.search(l, t, re.I)]
    label_only = bool(labels) and cov < 0.5
    unwanted = [a for a in case["avoid"] if re.search(a, pos, re.I) and not re.search(a, case["request"], re.I)]
    lint = base.lint(case["target"], prompt, negative, "prompt_only")
    ok = sem == 1 and cov >= 0.8 and not label_only and not unwanted and not lint
    return {"semantic": sem, "axis_coverage": cov, "missing_axes": sorted(set(axes) - set(hit)), "label_only": label_only,
            "unwanted": unwanted, "lint": lint, "words": base.words(base.strip_params(prompt)), "pass": ok}


def load(path=CASES):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def run():
    rows = []
    for c in load():
        a = c["request"]
        rows.append({"id": c["id"], "kind": c["kind"], "target": c["target"], "lang": c["lang"],
                     "A": score(c, a), "B": score(c, a.rstrip(" .") + LABEL_SUFFIX), "S": score(c, c["s_semantic"]),
                     "C": score(c, c["c_skill"], c.get("c_negative", ""))})
    return rows


def report(rows):
    m = lambda rs, arm, k: st.mean(float(r[arm][k]) for r in rs)
    L = ["# Style fidelity benchmark (prompt level)", "",
         "Generated by `python3 benchmarks/style_fidelity.py --report benchmarks/style-fidelity/REPORT.md`. "
         "**No images were generated.** This checks whether prompts describe the wanted look in visible terms; "
         "it does not show that a model will render it. See `benchmarks/style-fidelity/README.md`.", "",
         f"Cases: {len(rows)} ({', '.join(f'{k} {n}' for k, n in sorted(dict((k, sum(r['kind']==k for r in rows)) for k in {r['kind'] for r in rows}).items()))}).", "",
         "| Metric | A raw | B label stacking | S semantic only | C aesthetic translation |", "|---|---|---|---|---|"]
    for name, k, f in [("Semantic coverage", "semantic", lambda x: f"{x*100:.0f}%"),
                       ("Defining style axes described", "axis_coverage", lambda x: f"{x*100:.0f}%"),
                       ("Relies on style labels only", "label_only", lambda x: f"{x*100:.0f}%"),
                       ("Unwanted generic traits per prompt", "unwanted", None),
                       ("Mean words", "words", lambda x: f"{x:.0f}"),
                       ("Case pass (all checks)", "pass", lambda x: f"{x*100:.0f}%")]:
        if k == "unwanted":
            vals = [st.mean(len(r[a]["unwanted"]) for r in rows) for a in "ABSC"]
            L.append(f"| {name} | " + " | ".join(f"{v:.2f}" for v in vals) + " |")
        else:
            L.append(f"| {name} | " + " | ".join(f(m(rows, a, k)) for a in "ABSC") + " |")
    g = defaultdict(list)
    for r in rows:
        g[r["kind"]].append(r)
    L += ["", "## By case kind", "", "| Kind | n | Axis coverage S / C | Pass S / C |", "|---|---|---|---|"]
    for k in sorted(g):
        rs = g[k]
        L.append(f"| {k} | {len(rs)} | {m(rs,'S','axis_coverage')*100:.0f}% / {m(rs,'C','axis_coverage')*100:.0f}% | {m(rs,'S','pass')*100:.0f}% / {m(rs,'C','pass')*100:.0f}% |")
    fails = [r for r in rows if not r["C"]["pass"]]
    L += ["", "## C cases that fail", ""] + ([f"- `{r['id']}`: {r['C']}" for r in fails] or ["None."])
    L += ["", "## Reading these numbers", "",
          "- S has full semantic coverage but low style-axis coverage: the prompt-level form of \"right content, wrong style\". It fails by design.",
          "- B adds style labels without visible traits; label-only reliance is what the aesthetic engine replaces.",
          "- S prompts here are deliberately minimal content prompts; C length is in line with the main benchmark (mean 54 words) and within each adapter's band.",
          "- `intentional_generic` cases check that the engine keeps generic traits the user asked for.",
          "- C prompts and checks come from the same project: a regression baseline, not independent evidence.",
          f"- Visual verdict rule (tested with fixtures): success needs semantic ≥ {MIN_SEMANTIC}, aesthetic ≥ {MIN_AESTHETIC}, execution ≥ {MIN_EXECUTION}."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--report")
    a = ap.parse_args()
    text = report(run())
    if a.report:
        Path(a.report).write_text(text, encoding="utf-8")
    print(text)
